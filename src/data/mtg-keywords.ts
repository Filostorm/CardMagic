export function normalizeKeywordId(name: string): string {
  return name
    .trim()
    .toLowerCase()
    .replace(/&/g, "and")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

function createKeywordDefinitions(
  names: readonly string[],
  category: KeywordCategory,
): KeywordDefinition[] {
  return names.map((name) => {
    const id = normalizeKeywordId(name);
    const reminderText =
      category === "abilityWord" ? undefined : DEFAULT_REMINDER_TEXT[id];
    const helpText =
      category === "abilityWord" ? ABILITY_WORD_HELP_TEXT[id] : undefined;

    return {
      id,
      name,
      category,
      reminderText,
      helpText,
      icon: OFFICIAL_KEYWORD_ICON_IDS.has(id as KeywordIcon)
        ? (id as KeywordIcon)
        : undefined,
      arenaOnly: ARENA_KEYWORD_IDS.has(id) || undefined,
    };
  });
}

